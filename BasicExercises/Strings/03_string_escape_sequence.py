
#STRING ESCAPE SEQUENCE
str1 = "Hello my name is kinshuk guha."
str2 = "I want to be a Python developer"
print(str1, "\n", str2) # The \n uses to create a nextline to break the words into multiple lines.
print(str1, "\t", str2) # The \t gives a horizontal tab 
print("C:\\users\\documents") # The \ backslash is used for to print (\,'',"") in the string
print("Loading 0%", end="\r") #The \r is used to move the cursor back to the beginning of the current line without starting a new line.
print("Loading 100%")
print("ABC\bD") #The \b — backspace is used to remove a character followed by \b Typically displays ABD
print("Page 1\vPage 2") #The \v is used to give vertical tab
print("Warning!\a") #The \a — alert/bell is used to print a warning /alert message